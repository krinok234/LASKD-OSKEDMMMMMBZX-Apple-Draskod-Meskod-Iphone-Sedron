// Инициализация страницы правил
document.addEventListener('DOMContentLoaded', () => {
    if (window.location.pathname.includes('rules.html')) {
        initRules();
    }
});

function initRules() {
    const tabs = document.querySelectorAll('.rules-tab');
    const content = document.getElementById('rulesContent');
    
    // Загрузка первого раздела
    content.innerHTML = rulesContent.general;
    
    // Обработчики для табов
    tabs.forEach(tab => {
        tab.addEventListener('click', () => {
            // Убираем активный класс со всех табов
            tabs.forEach(t => t.classList.remove('active'));
            
            // Добавляем активный класс на текущий таб
            tab.classList.add('active');
            
            // Получаем секцию и загружаем контент
            const section = tab.dataset.section;
            content.innerHTML = rulesContent[section];
            
            // Плавная прокрутка к контенту
            content.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
        });
    });
}
